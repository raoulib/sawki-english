-- Sawki English : sécurisation des profils (audit d'octobre 2026)
--
-- Avant : la table user_profiles était lue et écrite avec la clé publique,
-- en filtrant par email. N'importe qui pouvait lire ou écraser un profil.
-- Après : chaque profil appartient à un utilisateur Supabase Auth (user_id),
-- et chacun ne voit et ne modifie que sa propre ligne.
--
-- Script idempotent : il peut être relancé sans casser les données.

-- 1. Table des profils (créée si absente, complétée sinon) ---------------
create table if not exists public.user_profiles (
  id                 bigint generated by default as identity primary key,
  email              text unique,
  name               text,
  current_level      text,
  target_goal        text,
  xp                 integer default 0,
  streak_days        integer default 1,
  completed_lessons  jsonb default '[]'::jsonb,
  evaluation_scores  jsonb default '{}'::jsonb,
  master_exam_score  integer,
  is_certified       boolean default false,
  is_premium         boolean default false,
  updated_at         timestamptz default now()
);

alter table public.user_profiles
  add column if not exists user_id uuid references auth.users (id) on delete cascade;

create unique index if not exists user_profiles_user_id_key
  on public.user_profiles (user_id);

-- 2. Remplissage automatique de user_id et email depuis la session ------
-- Le téléphone ne choisit ni le propriétaire de la ligne, ni l'email,
-- ni le statut Premium : ils viennent du serveur.
create or replace function public.user_profiles_set_owner()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null then
    new.user_id := auth.uid();
    new.email := nullif(lower(auth.jwt() ->> 'email'), '');
    if tg_op = 'INSERT' then
      new.is_premium := false;
    else
      new.is_premium := old.is_premium;
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists user_profiles_set_owner on public.user_profiles;
create trigger user_profiles_set_owner
  before insert or update on public.user_profiles
  for each row execute function public.user_profiles_set_owner();

-- 3. Règles d'accès (RLS) -------------------------------------------------
alter table public.user_profiles enable row level security;

-- Supprime toutes les anciennes règles (dont celles qui ouvraient la table).
do $$
declare
  pol record;
begin
  for pol in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'user_profiles'
  loop
    execute format('drop policy %I on public.user_profiles', pol.policyname);
  end loop;
end;
$$;

revoke all on public.user_profiles from anon;
grant select, insert, update, delete on public.user_profiles to authenticated;

create policy "Lire son profil" on public.user_profiles
  for select to authenticated using (user_id = auth.uid());

create policy "Créer son profil" on public.user_profiles
  for insert to authenticated with check (user_id = auth.uid());

create policy "Modifier son profil" on public.user_profiles
  for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "Supprimer son profil" on public.user_profiles
  for delete to authenticated using (user_id = auth.uid());

-- 4. Reprise des anciens profils (créés avant ce changement) -------------
-- Après vérification de son email par code, l'utilisateur récupère la ligne
-- qui portait cet email et n'avait pas encore de propriétaire.
create or replace function public.claim_legacy_profile()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := nullif(lower(auth.jwt() ->> 'email'), '');
  v_claimed integer;
begin
  if auth.uid() is null or v_email is null then
    return false;
  end if;

  if not exists (
    select 1 from public.user_profiles where lower(email) = v_email and user_id is null
  ) then
    return false;
  end if;

  -- Une ligne vide a pu être créée pour cet utilisateur avant la reprise :
  -- l'application garde la progression locale et la renverra fusionnée.
  delete from public.user_profiles where user_id = auth.uid();

  -- Une seule ligne est reprise (la plus récente), au cas où l'email
  -- apparaîtrait plusieurs fois dans les anciennes données.
  update public.user_profiles
     set user_id = auth.uid()
   where ctid = (
     select ctid from public.user_profiles
      where lower(email) = v_email and user_id is null
      order by updated_at desc nulls last
      limit 1
   );
  get diagnostics v_claimed = row_count;
  return v_claimed > 0;
end;
$$;

revoke all on function public.claim_legacy_profile() from public, anon;
grant execute on function public.claim_legacy_profile() to authenticated;

-- 5. Compteur d'usage de l'IA (limite quotidienne côté serveur) ----------
create table if not exists public.ai_usage (
  user_id uuid not null references auth.users (id) on delete cascade,
  day     date not null default current_date,
  kind    text not null check (kind in ('chat', 'tts')),
  count   integer not null default 0,
  primary key (user_id, day, kind)
);

alter table public.ai_usage enable row level security;
revoke all on public.ai_usage from anon, authenticated;

-- Appelée uniquement par la fonction serveur « gemini » (clé service_role).
create or replace function public.consume_ai_credit(p_user uuid, p_kind text, p_limit integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  insert into public.ai_usage (user_id, day, kind, count)
  values (p_user, current_date, p_kind, 1)
  on conflict (user_id, day, kind)
  do update set count = public.ai_usage.count + 1
  returning count into v_count;
  return v_count <= p_limit;
end;
$$;

revoke all on function public.consume_ai_credit(uuid, text, integer) from public, anon, authenticated;
grant execute on function public.consume_ai_credit(uuid, text, integer) to service_role;
